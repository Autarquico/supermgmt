package config

import (
	"fmt"
	"reflect"
	"slices"
	"sort"
	"strconv"
	"strings"
	"time"
)

const envPrefix = "SUPERMGMT_"

// InstallerEnvVars are the installer's own variables (spec §3.6). They are
// not configuration overrides and never produce an unknown-variable warning.
var InstallerEnvVars = []string{
	"SUPERMGMT_VERSION", "SUPERMGMT_CHANNEL", "SUPERMGMT_MODE", "SUPERMGMT_INSTALL_DIR",
	"SUPERMGMT_DATA_DIR", "SUPERMGMT_CONFIG_DIR", "SUPERMGMT_NONINTERACTIVE", "SUPERMGMT_YES",
	"SUPERMGMT_VMID", "SUPERMGMT_HOSTNAME", "SUPERMGMT_STORAGE", "SUPERMGMT_TEMPLATE_STORAGE",
	"SUPERMGMT_BRIDGE", "SUPERMGMT_NETWORK", "SUPERMGMT_IP", "SUPERMGMT_GATEWAY", "SUPERMGMT_DNS",
	"SUPERMGMT_CORES", "SUPERMGMT_MEMORY", "SUPERMGMT_SWAP", "SUPERMGMT_DISK_GIB", "SUPERMGMT_LOG_LEVEL",
}

// EnvVar describes one configuration override variable.
type EnvVar struct {
	Name     string // SUPERMGMT_SERVER_LISTEN
	YAMLPath string // server.listen
	Type     string // human-readable: string, bool, int, duration, list
	index    []int
	kind     leafKind
}

type leafKind int

const (
	leafString leafKind = iota
	leafBool
	leafOptionalBool
	leafInt
	leafDuration
	leafList
)

var leafTypeNames = map[leafKind]string{
	leafString: "string", leafBool: "bool", leafOptionalBool: "bool", leafInt: "int",
	leafDuration: "duration", leafList: "list (comma-separated)",
}

// EnvVars lists every override variable, generated by reflection over the
// yaml tags of Config: scalar leaves and string lists. Lists of structs
// (environments, providers) are configured in the file only. A name owned by
// the installer (SUPERMGMT_VERSION for `version`) is not an override.
func EnvVars() []EnvVar {
	var out []EnvVar
	for _, v := range collectLeaves(reflect.TypeFor[Config](), nil, "") {
		if !slices.Contains(InstallerEnvVars, v.Name) {
			out = append(out, v)
		}
	}
	return out
}

func collectLeaves(t reflect.Type, index []int, path string) []EnvVar {
	var out []EnvVar
	for i := range t.NumField() {
		f := t.Field(i)
		key := yamlKey(f)
		if key == "" {
			continue
		}
		fieldIndex := append(append([]int(nil), index...), i)
		fieldPath := joinPath(path, key)
		if f.Type.Kind() == reflect.Struct && f.Type != durationType {
			out = append(out, collectLeaves(f.Type, fieldIndex, fieldPath)...)
			continue
		}
		if kind, ok := leafKindOf(f.Type); ok {
			out = append(out, EnvVar{
				Name:     envPrefix + strings.ToUpper(strings.ReplaceAll(fieldPath, ".", "_")),
				YAMLPath: fieldPath,
				Type:     leafTypeNames[kind],
				index:    fieldIndex,
				kind:     kind,
			})
		}
	}
	return out
}

func leafKindOf(t reflect.Type) (leafKind, bool) {
	switch {
	case t == durationType:
		return leafDuration, true
	case t == reflect.TypeFor[*bool]():
		return leafOptionalBool, true
	case t == reflect.TypeFor[[]string]():
		return leafList, true
	}
	switch t.Kind() { //nolint:exhaustive // only these scalar kinds are overridable
	case reflect.String:
		return leafString, true
	case reflect.Bool:
		return leafBool, true
	case reflect.Int:
		return leafInt, true
	}
	return 0, false
}

// applyEnv overrides cfg from env ("KEY=value" entries) and returns the
// SUPERMGMT_ variables that are neither overrides nor installer variables.
func applyEnv(cfg *Config, env []string) (unknown []string, err error) {
	values := parseEnv(env)
	known := map[string]bool{}
	for _, name := range InstallerEnvVars {
		known[name] = true
	}
	root := reflect.ValueOf(cfg).Elem()
	var problems Problems
	for _, v := range EnvVars() {
		known[v.Name] = true
		raw, set := values[v.Name]
		if !set {
			continue
		}
		if err := setLeaf(root.FieldByIndex(v.index), v.kind, raw); err != nil {
			problems = append(problems, Problem{Path: v.YAMLPath, Message: fmt.Sprintf("%s: %v", v.Name, err)})
		}
	}
	for name := range values {
		if strings.HasPrefix(name, envPrefix) && !known[name] {
			unknown = append(unknown, name)
		}
	}
	sort.Strings(unknown)
	if len(problems) > 0 {
		return unknown, invalid("invalid environment override", problems)
	}
	return unknown, nil
}

func parseEnv(env []string) map[string]string {
	values := make(map[string]string, len(env))
	for _, kv := range env {
		if name, value, ok := strings.Cut(kv, "="); ok {
			values[name] = value
		}
	}
	return values
}

func setLeaf(dst reflect.Value, kind leafKind, raw string) error {
	switch kind {
	case leafString:
		dst.SetString(raw)
	case leafBool:
		b, err := strconv.ParseBool(raw)
		if err != nil {
			return fmt.Errorf("want a boolean, got %q", raw)
		}
		dst.SetBool(b)
	case leafOptionalBool:
		b, err := strconv.ParseBool(raw)
		if err != nil {
			return fmt.Errorf("want a boolean, got %q", raw)
		}
		dst.Set(reflect.ValueOf(&b))
	case leafInt:
		n, err := strconv.Atoi(raw)
		if err != nil {
			return fmt.Errorf("want an integer, got %q", raw)
		}
		dst.SetInt(int64(n))
	case leafDuration:
		d, err := time.ParseDuration(raw)
		if err != nil {
			return fmt.Errorf("want a duration such as 30s, got %q", raw)
		}
		dst.SetInt(int64(d))
	case leafList:
		dst.Set(reflect.ValueOf(splitList(raw)))
	}
	return nil
}

func splitList(raw string) []string {
	items := []string{}
	for _, item := range strings.Split(raw, ",") {
		if item = strings.TrimSpace(item); item != "" {
			items = append(items, item)
		}
	}
	return items
}
