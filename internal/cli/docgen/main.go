// Command docgen writes the sm command reference (docs/cli.md) from the cobra tree.
package main

//go:generate go run . -o ../../../docs/cli.md

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	"github.com/autarquico/supermgmt/internal/cli"
	"github.com/autarquico/supermgmt/internal/version"
)

const maxHeadingLevel = 6

func main() {
	out := flag.String("o", "", "write the reference to this file instead of stdout")
	flag.Parse()

	reference := render(cli.NewRootCommand(version.Build{}))
	if *out == "" {
		fmt.Print(reference)
		return
	}
	if err := os.WriteFile(*out, []byte(reference), 0o644); err != nil { //nolint:gosec // public documentation
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
}

// render returns the Markdown reference for root and every available command below it.
func render(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by internal/cli/docgen. Do not edit; run `make generate`. -->\n\n")
	b.WriteString("# Command reference\n\n")
	b.WriteString("Every `sm` command with its flags, generated from the program itself. ")
	b.WriteString("Run `sm <command> --help` for the same text in your terminal.\n")
	writeCommand(&b, root, 2)
	return b.String()
}

func writeCommand(b *strings.Builder, c *cobra.Command, level int) {
	fmt.Fprintf(b, "\n%s %s\n\n", strings.Repeat("#", min(level, maxHeadingLevel)), c.CommandPath())
	fmt.Fprintf(b, "%s\n\n", c.Short)
	if c.Long != "" && c.Long != c.Short {
		fmt.Fprintf(b, "%s\n\n", strings.TrimSpace(c.Long))
	}
	fmt.Fprintf(b, "```text\n%s\n```\n", c.UseLine())
	if len(c.Aliases) > 0 {
		fmt.Fprintf(b, "\nAliases: %s\n", codeList(c.Aliases))
	}
	if c.Example != "" {
		fmt.Fprintf(b, "\nExamples:\n\n```text\n%s\n```\n", strings.TrimSpace(c.Example))
	}
	writeFlags(b, c.NonInheritedFlags())
	if names := flagNames(c.InheritedFlags()); len(names) > 0 {
		fmt.Fprintf(b, "\nAlso accepts the global flags %s.\n", codeList(names))
	}
	for _, sub := range c.Commands() {
		if sub.IsAvailableCommand() {
			writeCommand(b, sub, level+1)
		}
	}
}

func writeFlags(b *strings.Builder, set *pflag.FlagSet) {
	var lines []string
	set.VisitAll(func(f *pflag.Flag) {
		if !f.Hidden {
			lines = append(lines, flagLine(f))
		}
	})
	if len(lines) == 0 {
		return
	}
	fmt.Fprintf(b, "\nFlags:\n\n%s\n", strings.Join(lines, "\n"))
}

func flagLine(f *pflag.Flag) string {
	name := "`--" + f.Name + "`"
	if f.Shorthand != "" {
		name += ", `-" + f.Shorthand + "`"
	}
	detail := f.Value.Type()
	if !isZeroDefault(f.DefValue) {
		detail += ", default `" + f.DefValue + "`"
	}
	return fmt.Sprintf("- %s (%s): %s", name, detail, f.Usage)
}

func isZeroDefault(value string) bool {
	switch value {
	case "", "false", "0", "[]", "0s":
		return true
	}
	return false
}

func flagNames(set *pflag.FlagSet) []string {
	var names []string
	set.VisitAll(func(f *pflag.Flag) {
		if !f.Hidden {
			names = append(names, "--"+f.Name)
		}
	})
	return names
}

func codeList(items []string) string {
	quoted := make([]string, len(items))
	for i, item := range items {
		quoted[i] = "`" + item + "`"
	}
	return strings.Join(quoted, ", ")
}
